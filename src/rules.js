// marked builds seven rules per indent width (0..3) and memoises them. Same here: one
// RegExp per width, built on first use.
function perIndent(make) {
  const cache = [];
  return (n) => {
    const slot = n < 1 ? 0 : n > 3 ? 3 : n - 1;
    return cache[slot] || (cache[slot] = make(slot));
  };
}

const itemCache = new Map();

/** The per-bullet list-item rule: `^( {0,3}<bullet>)((?:[\t ][^\\n]*)?(?:\\n|$))`. */
export function listItemRegex(bullet) {
  let re = itemCache.get(bullet);
  if (re === undefined) {
    re = new RegExp('^( {0,3}' + bullet + ')((?:[\t ][^\\n]*)?(?:\\n|$))');
    itemCache.set(bullet, re);
  }
  return re;
}

